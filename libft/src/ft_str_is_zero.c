#include "libft.h"

int	ft_str_is_zero(char *str)
{
	int	i;

	i = 0;
	if (str[i] == '-' || str[i] == '+')
		i++;
	while (str[i] && str[i] == '0')
		i++;
	if (i == (int)ft_strlen(str))
		return (1);
	return (0);
}
